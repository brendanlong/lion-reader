/**
 * EnhancedVoicesHelp Component
 *
 * Collapsible help section with FAQ about enhanced voices.
 * Provides user-friendly documentation about the enhanced TTS feature.
 *
 * @module components/narration/EnhancedVoicesHelp
 */

"use client";

import { useState } from "react";
import { PHONON_DOWNLOAD_SIZE_BYTES } from "@/lib/narration/enhanced-voices";
import { ChevronDownIcon, QuestionCircleIcon } from "@/components/ui/icons";

/**
 * FAQ item definition.
 */
interface FAQItem {
  question: string;
  answer: string;
}

/**
 * FAQ items for enhanced voices.
 */
const FAQ_ITEMS: FAQItem[] = [
  {
    question: "What are enhanced voices?",
    answer:
      "Enhanced voices are natural-sounding text-to-speech voices generated by Phonon, an open speech model that runs directly in your browser. Your articles never leave your device.",
  },
  {
    question: "Why use enhanced voices instead of browser voices?",
    answer:
      "Enhanced voices sound more natural and work the same in every browser, including Firefox where browser voices can have issues. They also work offline once downloaded, so you can listen to articles without an internet connection.",
  },
  {
    question: "How much storage do enhanced voices use?",
    answer: `About ${Math.round(PHONON_DOWNLOAD_SIZE_BYTES / (1024 * 1024))} MB: one model that every voice shares, plus a quarter of a megabyte for each voice.`,
  },
  {
    question: "Can I use enhanced voices offline?",
    answer:
      "Yes. Once downloaded, the model and every voice are stored in your browser and work without an internet connection.",
  },
  {
    question: "How do I free up storage space?",
    answer:
      "Click the trash icon next to the voice model to delete it. You can download it again at any time.",
  },
];

/**
 * Individual FAQ item component with expand/collapse functionality.
 */
function FAQItemComponent({
  item,
  isOpen,
  onToggle,
}: {
  item: FAQItem;
  isOpen: boolean;
  onToggle: () => void;
}) {
  return (
    <div className="border-edge-strong border-b last:border-b-0">
      <button
        type="button"
        onClick={onToggle}
        className="flex w-full items-center justify-between py-3 text-left"
        aria-expanded={isOpen}
      >
        <span className="ui-text-sm text-body font-medium">{item.question}</span>
        <ChevronDownIcon
          className={`text-muted h-4 w-4 flex-shrink-0 transition-transform duration-200 ${
            isOpen ? "rotate-180" : ""
          }`}
        />
      </button>
      {isOpen && (
        <div className="pr-8 pb-3">
          <p className="ui-text-sm text-muted">{item.answer}</p>
        </div>
      )}
    </div>
  );
}

/**
 * Enhanced voices help section with collapsible FAQ.
 *
 * Displays a "Help with enhanced voices" button that expands to show
 * frequently asked questions about the enhanced TTS feature.
 *
 * @returns The enhanced voices help component.
 *
 * @example
 * ```tsx
 * function NarrationSettings() {
 *   return (
 *     <div>
 *       <EnhancedVoiceList ... />
 *       <EnhancedVoicesHelp />
 *     </div>
 *   );
 * }
 * ```
 */
export function EnhancedVoicesHelp() {
  const [isExpanded, setIsExpanded] = useState(false);
  const [openItemIndex, setOpenItemIndex] = useState<number | null>(null);

  const handleToggleItem = (index: number) => {
    setOpenItemIndex(openItemIndex === index ? null : index);
  };

  return (
    <div className="border-edge-strong rounded-lg border">
      {/* Header button */}
      <button
        type="button"
        onClick={() => setIsExpanded(!isExpanded)}
        className="hover:bg-surface-muted flex w-full items-center justify-between px-4 py-3 text-left"
        aria-expanded={isExpanded}
      >
        <div className="flex items-center gap-2">
          <QuestionCircleIcon className="text-muted h-4 w-4" />
          <span className="ui-text-sm text-body font-medium">Help with enhanced voices</span>
        </div>
        <ChevronDownIcon
          className={`text-muted h-4 w-4 transition-transform duration-200 ${
            isExpanded ? "rotate-180" : ""
          }`}
        />
      </button>

      {/* Expandable FAQ content */}
      {isExpanded && (
        <div className="border-edge-strong border-t px-4">
          {FAQ_ITEMS.map((item, index) => (
            <FAQItemComponent
              key={index}
              item={item}
              isOpen={openItemIndex === index}
              onToggle={() => handleToggleItem(index)}
            />
          ))}
        </div>
      )}
    </div>
  );
}
