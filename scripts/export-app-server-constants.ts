/**
 * Writes the server's request limits, upload file types and cloud-speech settings, and
 * the web's narration cues and enhanced voices, that the native app must agree with, as Kotlin constants, so a server change reaches
 * the app instead of a stale copy. Regenerate with `pnpm app:server-constants`;
 * a unit test fails when the committed copy is stale.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  CLOUD_SPEECH_PAUSE_STEP_SECONDS,
  DEFAULT_CLOUD_SPEECH_PAUSE_SECONDS,
  MAX_CLOUD_SPEECH_CHARS,
  MAX_CLOUD_SPEECH_PAUSE_SECONDS,
  MAX_CLOUD_SPEECH_STREAMS,
  PREVIEW_TEXT,
} from "../src/lib/narration/constants";
import {
  ENHANCED_VOICES,
  enhancedVoiceUrl,
  PHONON_DOWNLOAD_SIZE_BYTES,
  PHONON_MODEL_FILES,
  resolveEnhancedVoice,
} from "../src/lib/narration/enhanced-voices";
import { NEXT_ARTICLE, NO_MORE_ARTICLES } from "../src/lib/narration/paragraph-map";
import { EBOOK_UPLOAD_EXTENSIONS, SUPPORTED_UPLOAD_EXTENSIONS } from "../src/lib/upload-file-types";
import {
  DEFAULT_MAX_SAVED_ARTICLE_SIZE_BYTES,
  maxEbookUploadBytes,
} from "../src/lib/upload-limits";
import { MAX_ENTRIES_PAGE_SIZE } from "../src/server/services/entries";
import { MAX_ENTRY_STATE_BATCH } from "../src/server/services/entry-state";
import { MAX_SYNC_PAGE_ENTRIES } from "../src/server/services/sync";

export const APP_SERVER_CONSTANTS_PATH =
  "kmp/shared/src/commonMain/kotlin/com/lionreader/shared/api/ServerConstants.kt";

function int(value: number): string {
  if (!Number.isInteger(value)) throw new Error(`${value} is not an integer`);
  return String(value);
}

function float(value: number): string {
  return `${value}f`;
}

/** A `const val` in an object, wrapped as ktfmt (Spotless) wraps one past 100 columns. */
function constVal(name: string, value: string): string {
  const line = `    const val ${name} = ${value}`;
  return line.length > 100 ? `    const val ${name} =\n        ${value}` : line;
}

function string(value: string): string {
  // JSON's escapes are Kotlin's, but for `$`, which starts a template there.
  return JSON.stringify(value).replaceAll("$", "\\$");
}

export function renderAppServerConstants(): string {
  return `// Generated by \`pnpm app:server-constants\` (scripts/export-app-server-constants.ts) from the
// server's and web's constants. Don't edit: a unit test fails when it's stale.

package com.lionreader.shared.api

/** What the server accepts in one request. */
object ServerLimits {
    /** Ids per \`/entries/batch\` request, and the largest \`/entries\` \`limit\`. */
    const val ENTRIES_PAGE_SIZE = ${int(MAX_ENTRIES_PAGE_SIZE)}

    /** Entries per \`/entries/mark-read\` or \`/entries/starred\` request. */
    const val STATE_WRITE_ENTRIES = ${int(MAX_ENTRY_STATE_BATCH)}

    /** Entries in one \`/sync/changes\` page. */
    const val SYNC_PAGE_ENTRIES = ${int(MAX_SYNC_PAGE_ENTRIES)}

    /** Characters per \`/narration/speech\` request. */
    const val CLOUD_SPEECH_CHARS = ${int(MAX_CLOUD_SPEECH_CHARS)}

    /**
     * Bytes of a file \`/saved/upload\` accepts, by default: a server can set its own limit, and says
     * so when a file is over it.
     */
    const val UPLOAD_BYTES = ${int(DEFAULT_MAX_SAVED_ARTICLE_SIZE_BYTES)}

    /** Bytes of an ebook \`/collections/import-ebook\` accepts, by default, as for [UPLOAD_BYTES]. */
    const val EBOOK_UPLOAD_BYTES = ${int(maxEbookUploadBytes(DEFAULT_MAX_SAVED_ARTICLE_SIZE_BYTES))}
}

/** File extensions \`/saved/upload\` converts; it picks the converter by the filename's. */
val UPLOAD_EXTENSIONS: List<String> =
    listOf(${SUPPORTED_UPLOAD_EXTENSIONS.map((ext) => JSON.stringify(ext)).join(", ")})

/** File extensions \`/collections/import-ebook\` imports as a collection of chapters. */
val EBOOK_UPLOAD_EXTENSIONS: List<String> = listOf(${EBOOK_UPLOAD_EXTENSIONS.map((ext) => JSON.stringify(ext)).join(", ")})

/** The silence after each chunk of cloud speech (\`pauseSeconds\`), as the web sets it. */
object CloudSpeechPause {
    const val DEFAULT_SECONDS = ${float(DEFAULT_CLOUD_SPEECH_PAUSE_SECONDS)}

    /** The most the server accepts. */
    const val MAX_SECONDS = ${float(MAX_CLOUD_SPEECH_PAUSE_SECONDS)}

    /** The settings slider's step. */
    const val STEP_SECONDS = ${float(CLOUD_SPEECH_PAUSE_STEP_SECONDS)}
}

/**
 * Cloud speech requests one listener streams at once, as on the web: providers limit concurrent
 * requests per key, which several listeners share on the server's.
 */
const val MAX_CLOUD_SPEECH_STREAMS = ${int(MAX_CLOUD_SPEECH_STREAMS)}

/** What narration says after an article's "End of article." when it goes on through a list. */
object NarrationCues {
    /** It goes on to the next article. */
    const val NEXT_ARTICLE = ${string(NEXT_ARTICLE)}

    /** It would go on, but the list has ended. */
    const val NO_MORE_ARTICLES = ${string(NO_MORE_ARTICLES)}

    /** What a voice's preview says. */
    const val PREVIEW = ${string(PREVIEW_TEXT)}
}

/**
 * Enhanced voices (Phonon), as the web has them: the same files, by the same pinned URLs, so a
 * voice id means the same voice on both.
 */
object EnhancedVoiceFiles {
${constVal("WEIGHTS", string(PHONON_MODEL_FILES.weights))}
${constVal("TOKENIZER", string(PHONON_MODEL_FILES.tokenizer))}
${constVal("CONFIG", string(PHONON_MODEL_FILES.config))}

    /** The model and every voice. */
    const val DOWNLOAD_BYTES = ${int(PHONON_DOWNLOAD_SIZE_BYTES)}L

    /** Spoken when none is picked, or the picked one isn't offered. */
    const val DEFAULT_VOICE = ${string(resolveEnhancedVoice(null).id)}
}

/** An enhanced voice: its catalog id, what it's called, and its file. */
data class EnhancedVoice(
    val id: String,
    val name: String,
    /** \`en-US\` or \`en-GB\`. */
    val locale: String,
    val description: String,
    val url: String,
)

val ENHANCED_VOICES: List<EnhancedVoice> =
    listOf(
${ENHANCED_VOICES.map(
  (voice) =>
    `        EnhancedVoice(\n${[voice.id, voice.name, voice.locale, voice.description, enhancedVoiceUrl(voice.id)].map((value) => `            ${string(value)},\n`).join("")}        ),`
).join("\n")}
    )
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(APP_SERVER_CONSTANTS_PATH, renderAppServerConstants());
  console.log(`Wrote ${APP_SERVER_CONSTANTS_PATH}`);
}
