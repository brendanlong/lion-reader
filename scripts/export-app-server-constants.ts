/**
 * Writes the server's request limits and cloud-speech pause settings the
 * native app must agree with, as Kotlin constants, so a server change reaches
 * the app instead of a stale copy. Regenerate with `pnpm app:server-constants`;
 * a unit test fails when the committed copy is stale.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  CLOUD_SPEECH_PAUSE_STEP_SECONDS,
  DEFAULT_CLOUD_SPEECH_PAUSE_SECONDS,
  MAX_CLOUD_SPEECH_CHARS,
  MAX_CLOUD_SPEECH_PAUSE_SECONDS,
} from "../src/lib/narration/constants";
import { MAX_ENTRIES_PAGE_SIZE } from "../src/server/services/entries";
import { MAX_ENTRY_STATE_BATCH } from "../src/server/services/entry-state";
import { MAX_SYNC_PAGE_ENTRIES } from "../src/server/services/sync";

export const APP_SERVER_CONSTANTS_PATH =
  "kmp/shared/src/commonMain/kotlin/com/lionreader/shared/api/ServerConstants.kt";

function int(value: number): string {
  if (!Number.isInteger(value)) throw new Error(`${value} is not an integer`);
  return String(value);
}

function float(value: number): string {
  return `${value}f`;
}

export function renderAppServerConstants(): string {
  return `// Generated by \`pnpm app:server-constants\` (scripts/export-app-server-constants.ts) from the
// server's constants. Don't edit: a unit test fails when it's stale.

package com.lionreader.shared.api

/** What the server accepts in one request. */
object ServerLimits {
    /** Ids per \`/entries/batch\` request, and the largest \`/entries\` \`limit\`. */
    const val ENTRIES_PAGE_SIZE = ${int(MAX_ENTRIES_PAGE_SIZE)}

    /** Entries per \`/entries/mark-read\` or \`/entries/starred\` request. */
    const val STATE_WRITE_ENTRIES = ${int(MAX_ENTRY_STATE_BATCH)}

    /** Entries in one \`/sync/changes\` page. */
    const val SYNC_PAGE_ENTRIES = ${int(MAX_SYNC_PAGE_ENTRIES)}

    /** Characters per \`/narration/speech\` request. */
    const val CLOUD_SPEECH_CHARS = ${int(MAX_CLOUD_SPEECH_CHARS)}
}

/** The silence after each chunk of cloud speech (\`pauseSeconds\`), as the web sets it. */
object CloudSpeechPause {
    const val DEFAULT_SECONDS = ${float(DEFAULT_CLOUD_SPEECH_PAUSE_SECONDS)}

    /** The most the server accepts. */
    const val MAX_SECONDS = ${float(MAX_CLOUD_SPEECH_PAUSE_SECONDS)}

    /** The settings slider's step. */
    const val STEP_SECONDS = ${float(CLOUD_SPEECH_PAUSE_STEP_SECONDS)}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(APP_SERVER_CONSTANTS_PATH, renderAppServerConstants());
  console.log(`Wrote ${APP_SERVER_CONSTANTS_PATH}`);
}
